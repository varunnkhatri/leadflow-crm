def generate_synthetic_sentiment() -> pd.DataFrame:
    rows = [
        {
            "text": text,
            "sentiment": label,
            "topic": topic,
            "is_synthetic": True,
            "dataset_provenance": "synthetic_leadflow_sentiment_v2",
        }
        for label, items in EXAMPLES.items()
        for text, topic in items
    ]
    return pd.DataFrame(rows)


